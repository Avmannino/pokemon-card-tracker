-- Sports cards in the portfolio chart and performance numbers.
--
-- CardSight's terms don't allow keeping its card prices over time, so the
-- chart gets only your sports collection's total value: one row after each
-- change (a card added, removed or edited, or a price refresh). No card or
-- price from CardSight is stored here.
--
-- flow is the part of the change that came from you (cards added, removed,
-- regraded or given your own value, and cards priced for the first time),
-- which the chart treats like a deposit or withdrawal. The rest of the
-- change is market movement.
--
-- Safe to re-run.

create table if not exists public.sports_value_history (
    id bigint generated by default as identity primary key,
    recorded_at timestamptz not null default now(),
    total_value numeric(12, 2) not null check (total_value >= 0),
    flow numeric(12, 2) not null default 0,
    kind text not null
        check (kind in ('add', 'remove', 'quantity', 'edit', 'refresh')),
    created_at timestamptz not null default now()
);

create index if not exists idx_sports_value_history_recorded
    on public.sports_value_history(recorded_at, id);

alter table public.sports_value_history enable row level security;
